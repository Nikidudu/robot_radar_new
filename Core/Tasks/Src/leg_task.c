LegPos leftLegPos, rightLegPos;
extern Motor leftJoint[2], rightJoint[2], leftWheel, rightWheel;

void leg_task(void *argument) {
	float legPos[2], legSpd[2];
	const float lpfRatio = 0.5f; //低通滤波系数(新值的权重)
	float lastLeftDLength = 0, lastRightDLength = 0;
    while (1) {

    	leg_pos(leftJoint[0].angle, leftJoint[1].angle, legPos);
    	leftLegPos.length = legPos[0];
    	leftLegPos.angle = legPos[1];
    	leg_spd(leftJoint[0].speed, leftJoint[1].speed, leftJoint[0].angle, leftJoint[1].angle, legSpd);
    	leftLegPos.dLength = legSpd[0];
    	leftLegPos.dAngle = legSpd[1];
    	leftLegPos.ddLength = ((leftLegPos.dLength - lastLeftDLength) * 1000 / 5) * lpfRatio + leftLegPos.ddLength * (1 - lpfRatio);
    	lastLeftDLength = leftLegPos.dLength;
    	leg_pos(rightJoint[0].angle, rightJoint[1].angle, legPos);
    	rightLegPos.length = legPos[0];
    	rightLegPos.angle = legPos[1];
    	leg_spd(rightJoint[0].speed, rightJoint[1].speed, rightJoint[0].angle, rightJoint[1].angle, legSpd);
    	rightLegPos.dLength = legSpd[0];
    	rightLegPos.dAngle = legSpd[1];
    	rightLegPos.ddLength = ((rightLegPos.dLength - lastRightDLength) * 1000 / 5) * lpfRatio + rightLegPos.ddLength * (1 - lpfRatio);
    	lastRightDLength = rightLegPos.dLength;
    	vTaskDelay(5);
    }
}


